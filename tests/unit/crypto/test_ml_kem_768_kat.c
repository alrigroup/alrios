    test_fips203_kat_vector_0();
    test_fips203_kat_vector_1();
    test_roundtrip_and_corruption();

    (void)printf("MP-005 (FIPS 203 ML-KEM-768 KAT & Channel Key Encapsulation): PASS\n");
    return EXIT_SUCCESS;
