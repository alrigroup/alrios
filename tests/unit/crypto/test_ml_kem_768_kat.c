static void test_roundtrip_and_corruption(void) {
#if defined(ALRIOS_HAVE_ML_KEM_768)
    uint8_t pk[ML_KEM_768_PUBLIC_KEY_LEN];
    uint8_t sk[ML_KEM_768_SECRET_KEY_LEN];
    uint8_t ct[ML_KEM_768_CIPHERTEXT_LEN];
    uint8_t ss_enc[ML_KEM_768_SHARED_SECRET_LEN];
    uint8_t ss_dec[ML_KEM_768_SHARED_SECRET_LEN];
    uint8_t ss_corrupt[ML_KEM_768_SHARED_SECRET_LEN];

    CHECK(alrios_ml_kem_768_keypair(pk, sk) == ALRIOS_CRYPTO_OK);
    CHECK(alrios_ml_kem_768_encapsulate(pk, ct, ss_enc) == ALRIOS_CRYPTO_OK);
    CHECK(alrios_ml_kem_768_decapsulate(sk, ct, ss_dec) == ALRIOS_CRYPTO_OK);
    CHECK(alrios_constant_time_memcmp(ss_enc, ss_dec, ML_KEM_768_SHARED_SECRET_LEN) == 0);

    ct[0] ^= 0x01U;
    CHECK(alrios_ml_kem_768_decapsulate(sk, ct, ss_corrupt) == ALRIOS_CRYPTO_OK);
    CHECK(alrios_constant_time_memcmp(ss_enc, ss_corrupt, ML_KEM_768_SHARED_SECRET_LEN) != 0);

    ct[0] ^= 0x01U;
    ct[ML_KEM_768_CIPHERTEXT_LEN - 1] ^= 0x80U;
    CHECK(alrios_ml_kem_768_decapsulate(sk, ct, ss_corrupt) == ALRIOS_CRYPTO_OK);
    CHECK(alrios_constant_time_memcmp(ss_enc, ss_corrupt, ML_KEM_768_SHARED_SECRET_LEN) != 0);

    ct[ML_KEM_768_CIPHERTEXT_LEN - 1] ^= 0x80U;
    CHECK(alrios_ml_kem_768_decapsulate(sk, ct, ss_dec) == ALRIOS_CRYPTO_OK);
    CHECK(alrios_constant_time_memcmp(ss_enc, ss_dec, ML_KEM_768_SHARED_SECRET_LEN) == 0);

    uint8_t bad_pk[ML_KEM_768_PUBLIC_KEY_LEN];
    memcpy(bad_pk, pk, sizeof(bad_pk));
    bad_pk[0] ^= 0xffU;
    bad_pk[1] ^= 0xffU;
    int res = alrios_ml_kem_768_encapsulate(bad_pk, ct, ss_enc);
    CHECK(res == ALRIOS_CRYPTO_OK || res == ALRIOS_CRYPTO_ERR_INVALID_KEY);

    alrios_explicit_zeroize(pk, sizeof(pk));
    alrios_explicit_zeroize(sk, sizeof(sk));
    alrios_explicit_zeroize(ct, sizeof(ct));
    alrios_explicit_zeroize(ss_enc, sizeof(ss_enc));
    alrios_explicit_zeroize(ss_dec, sizeof(ss_dec));
    alrios_explicit_zeroize(ss_corrupt, sizeof(ss_corrupt));
#else
    uint8_t pk[ML_KEM_768_PUBLIC_KEY_LEN] = {0};
    uint8_t sk[ML_KEM_768_SECRET_KEY_LEN] = {0};
    uint8_t ct[ML_KEM_768_CIPHERTEXT_LEN] = {0};
    uint8_t ss[ML_KEM_768_SHARED_SECRET_LEN] = {0};
    CHECK(alrios_ml_kem_768_keypair(pk, sk) == ALRIOS_CRYPTO_ERR_UNAVAILABLE);
    CHECK(alrios_ml_kem_768_encapsulate(pk, ct, ss) == ALRIOS_CRYPTO_ERR_UNAVAILABLE);
    CHECK(alrios_ml_kem_768_decapsulate(sk, ct, ss) == ALRIOS_CRYPTO_ERR_UNAVAILABLE);
#endif
}

