#define CHECK(condition) do { \
    if (!(condition)) { \
        (void)fprintf(stderr, "CHECK failed at %s:%d: %s\n", \
                      __FILE__, __LINE__, #condition); \
        exit(EXIT_FAILURE); \
    } \
} while (0)

static void fill_sequence(uint8_t *buffer, size_t length, uint8_t start) {
    size_t index;

    for (index = 0U; index < length; ++index) {
        buffer[index] = (uint8_t)(start + (uint8_t)index);
    }
}

static int is_all_zero(const uint8_t *buffer, size_t length) {
    uint8_t accumulator = 0U;
    size_t index;

    for (index = 0U; index < length; ++index) {
        accumulator |= buffer[index];
    }
    return accumulator == 0U;
}

static void test_null_arguments(void) {
    uint8_t public_key[ML_KEM_768_PUBLIC_KEY_LEN];
    uint8_t secret_key[ML_KEM_768_SECRET_KEY_LEN];
    uint8_t ciphertext[ML_KEM_768_CIPHERTEXT_LEN];
    uint8_t shared_secret[ML_KEM_768_SHARED_SECRET_LEN];

    CHECK(alrios_ml_kem_768_keypair(NULL, secret_key) == ALRIOS_CRYPTO_ERR_NULL_PTR);
    CHECK(alrios_ml_kem_768_keypair(public_key, NULL) == ALRIOS_CRYPTO_ERR_NULL_PTR);
    CHECK(alrios_ml_kem_768_encaps(NULL, ciphertext, shared_secret) == ALRIOS_CRYPTO_ERR_NULL_PTR);
    CHECK(alrios_ml_kem_768_encaps(public_key, NULL, shared_secret) == ALRIOS_CRYPTO_ERR_NULL_PTR);
    CHECK(alrios_ml_kem_768_decaps(NULL, ciphertext, shared_secret) == ALRIOS_CRYPTO_ERR_NULL_PTR);
    CHECK(alrios_ml_kem_768_decaps(secret_key, NULL, shared_secret) == ALRIOS_CRYPTO_ERR_NULL_PTR);
}

static void test_provider_behavior(void) {
    uint8_t encaps_seed[ML_KEM_768_ENCAPS_SEED_LEN];
    uint8_t public_key_a[ML_KEM_768_PUBLIC_KEY_LEN];
    uint8_t public_key_b[ML_KEM_768_PUBLIC_KEY_LEN];
    uint8_t secret_key_a[ML_KEM_768_SECRET_KEY_LEN];
    uint8_t secret_key_b[ML_KEM_768_SECRET_KEY_LEN];
    uint8_t ciphertext_a[ML_KEM_768_CIPHERTEXT_LEN];
    uint8_t ciphertext_b[ML_KEM_768_CIPHERTEXT_LEN];
    uint8_t corrupted_ciphertext[ML_KEM_768_CIPHERTEXT_LEN];
    uint8_t sender_secret_a[ML_KEM_768_SHARED_SECRET_LEN];
    uint8_t sender_secret_b[ML_KEM_768_SHARED_SECRET_LEN];
    uint8_t receiver_secret[ML_KEM_768_SHARED_SECRET_LEN];
    uint8_t corrupted_secret[ML_KEM_768_SHARED_SECRET_LEN];
    int result;

    fill_sequence(encaps_seed, sizeof(encaps_seed), 0xa0U);
    (void)memset(public_key_a, 0xa5, sizeof(public_key_a));
    (void)memset(secret_key_a, 0xa5, sizeof(secret_key_a));

    if (!alrios_ml_kem_768_provider_available()) {
        result = alrios_ml_kem_768_keypair(public_key_a, secret_key_a);
        CHECK(result == ALRIOS_CRYPTO_ERR_UNAVAILABLE);
        CHECK(is_all_zero(public_key_a, sizeof(public_key_a)));
        CHECK(is_all_zero(secret_key_a, sizeof(secret_key_a)));
        CHECK(!alrios_crypto_has_capability(ALRIOS_CRYPTO_CAP_ML_KEM_768));
        return;
    }

    CHECK(alrios_crypto_has_capability(ALRIOS_CRYPTO_CAP_ML_KEM_768));
    CHECK(alrios_ml_kem_768_keypair_from_seed(
              nist_keygen_seed_26, public_key_a, secret_key_a
          ) == ALRIOS_CRYPTO_OK);
    CHECK(memcmp(public_key_a, nist_keygen_public_key_26, sizeof(public_key_a)) == 0);
    CHECK(memcmp(secret_key_a, nist_keygen_secret_key_26, sizeof(secret_key_a)) == 0);
    CHECK(alrios_ml_kem_768_keypair_from_seed(
              nist_keygen_seed_26, public_key_b, secret_key_b
          ) == ALRIOS_CRYPTO_OK);
    CHECK(memcmp(public_key_a, public_key_b, sizeof(public_key_a)) == 0);
    CHECK(memcmp(secret_key_a, secret_key_b, sizeof(secret_key_a)) == 0);

    CHECK(alrios_ml_kem_768_encaps_from_seed(
              public_key_a,
              encaps_seed,
              ciphertext_a,
              sender_secret_a
          ) == ALRIOS_CRYPTO_OK);
    CHECK(alrios_ml_kem_768_encaps_from_seed(
              public_key_a,
              encaps_seed,
              ciphertext_b,
              sender_secret_b
          ) == ALRIOS_CRYPTO_OK);
    CHECK(memcmp(ciphertext_a, ciphertext_b, sizeof(ciphertext_a)) == 0);
    CHECK(memcmp(sender_secret_a, sender_secret_b, sizeof(sender_secret_a)) == 0);

    CHECK(alrios_ml_kem_768_decaps(
              secret_key_a,
              ciphertext_a,
              receiver_secret
          ) == ALRIOS_CRYPTO_OK);
    CHECK(memcmp(sender_secret_a, receiver_secret, sizeof(sender_secret_a)) == 0);

    (void)memcpy(corrupted_ciphertext, ciphertext_a, sizeof(corrupted_ciphertext));
    corrupted_ciphertext[ML_KEM_768_CIPHERTEXT_LEN / 2U] ^= 0x01U;
    CHECK(alrios_ml_kem_768_decaps(
              secret_key_a,
              corrupted_ciphertext,
              corrupted_secret
          ) == ALRIOS_CRYPTO_OK);
    CHECK(memcmp(sender_secret_a, corrupted_secret, sizeof(sender_secret_a)) != 0);
}

