    CHECK(alrios_ml_kem_768_keypair_from_seed(seed, NULL, sk) == ALRIOS_CRYPTO_ERR_NULL_PTR);
    CHECK(alrios_ml_kem_768_keypair_from_seed(seed, pk, NULL) == ALRIOS_CRYPTO_ERR_NULL_PTR);

    CHECK(alrios_ml_kem_768_encapsulate(NULL, ct, ss) == ALRIOS_CRYPTO_ERR_NULL_PTR);
    CHECK(alrios_ml_kem_768_encapsulate(pk, NULL, ss) == ALRIOS_CRYPTO_ERR_NULL_PTR);
    CHECK(alrios_ml_kem_768_encapsulate(pk, ct, NULL) == ALRIOS_CRYPTO_ERR_NULL_PTR);

    CHECK(alrios_ml_kem_768_decapsulate(NULL, ct, ss) == ALRIOS_CRYPTO_ERR_NULL_PTR);
    CHECK(alrios_ml_kem_768_decapsulate(sk, NULL, ss) == ALRIOS_CRYPTO_ERR_NULL_PTR);
